# PHASE9_COPY.md (PHASE9.md 2.11): every TRANSLATIONS key phase 9 changed, added or removed, old → new, in en, fr, es and tr, from
# master's deploy/index.html and the working copy. A key absent from a language on master shows "(missing: English
# was shown)". Usage: python3 scripts/design-verify/phase9/copydoc9.py > design/house-lights/PHASE9_COPY.md
import re, subprocess, os
ROOT = os.path.join(os.path.dirname(__file__), '../../..')
def table(src):
    T = {}; cur = None
    for line in src.split('\n'):
        m = re.match(r'^  (en|fr|es|tr): *\{', line)
        if m: cur = m.group(1); T[cur] = {}; continue
        if cur and re.match(r'^  \};?\s*$', line): cur = None; continue
        if cur:
            for m in re.finditer(r"""([A-Za-z0-9_]+)\s*:\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`)""", line):
                T[cur][m.group(1)] = m.group(2)[1:-1].replace("\\'", "'").replace('\\"', '"')
    return T
old = table(subprocess.run(['git', 'show', 'master:deploy/index.html'], cwd=ROOT, capture_output=True, text=True).stdout)
new = table(open(os.path.join(ROOT, 'deploy/index.html'), encoding='utf8').read())
keys = sorted(k for k in set(new['en']) | set(old['en']) if any(new[l].get(k) != old[l].get(k) for l in ('en', 'fr', 'es', 'tr')))
esc = lambda v: (v or '').replace('|', '\\|').replace('\n', ' ')
print('# Phase 9 copy: everything else (old → new)\n')
print('Generated by `scripts/design-verify/phase9/copydoc9.py` from master and redesign/phase9 (PHASE9.md 2.11). Every')
print('TRANSLATIONS key phase 9 changed, added or removed, per language. "(new key)" had no value on master; "(removed)"')
print('is a key whose markup is gone (the Pricing developer disclosure, the sign-up feature list and banner, Vocal Lab\'s')
print('note-count suffix). English literals moved out of the code into keys are in this table too: the Feedback toasts, the')
print('poster export toast, the clip recorders\' labels and toasts, the Key tool\'s ranking labels. Markup defaults that')
print('`data-i18n` replaces at run time and that still carried a §7 word or an emoji were set to the key\'s English.\n')
print(f'{len(keys)} keys.\n')
print('| Key | Lang | Old | New |\n|---|---|---|---|')
for k in keys:
    for l in ('en', 'fr', 'es', 'tr'):
        o, n = old[l].get(k), new[l].get(k)
        if o == n: continue
        ov = '(new key)' if o is None and old['en'].get(k) is None else ('(missing: English was shown)' if o is None else esc(o))
        nv = '(removed)' if n is None and new['en'].get(k) is None else esc(n)
        print(f'| `{k}` | {l} | {ov} | {nv} |')
