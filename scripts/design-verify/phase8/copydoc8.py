# PHASE8_COPY.md (PHASE8.md 2.9): every TRANSLATIONS key phase 8 changed or added, old → new, in en, fr, es and tr, from
# master's deploy/index.html and the working copy. A key absent from a language on master shows "(missing: English
# was shown)". Usage: python3 scripts/design-verify/phase8/copydoc8.py > design/house-lights/PHASE8_COPY.md
import re, subprocess, os
ROOT = os.path.join(os.path.dirname(__file__), '../../..')
def table(src):
    T = {}; cur = None
    for line in src.split('\n'):
        m = re.match(r'^  (en|fr|es|tr): *\{', line)
        if m: cur = m.group(1); T[cur] = {}; continue
        if cur and re.match(r'^  \};?\s*$', line): cur = None; continue
        if cur:
            for m in re.finditer(r"""([A-Za-z0-9_]+)\s*:\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`)""", line):
                T[cur][m.group(1)] = m.group(2)[1:-1].replace("\\'", "'").replace('\\"', '"')
    return T
old = table(subprocess.run(['git', 'show', 'master:deploy/index.html'], cwd=ROOT, capture_output=True, text=True).stdout)
new = table(open(os.path.join(ROOT, 'deploy/index.html'), encoding='utf8').read())
keys = sorted(k for k in new['en'] if any(new[l].get(k) != old[l].get(k) for l in ('en', 'fr', 'es', 'tr')))
esc = lambda v: (v or '').replace('|', '\\|').replace('\n', ' ')
print('# Phase 8 copy: Vocal World (old → new)\n')
print('Generated by `scripts/design-verify/phase8/copydoc8.py` from master and redesign/phase8 (PHASE8.md 2.9). Every')
print('TRANSLATIONS key phase 8 changed or added, per language. "(new key)" had no value on master; "(missing: English')
print('was shown)" means that language had no value, so the English showed. English literals removed from code (the')
print('status lines "Flying — tap to stop", "Battling — tap to flee", "Running — tap to stop", "Singing — tap to stop",')
print('"Stop", "Score: ", "🪙 … · Combo: ", "HEAD LANE", "CHEST LANE", the lock toast, "Now practicing: …", the Boss\'s')
print('"Why?" text, the section names, the Glider\'s adaptive notes, the Harmony mode toggles\' "On/Off" labels) are')
print('now keys in this table.\n')
print(f'{len(keys)} keys.\n')
print('| Key | Lang | Old | New |\n|---|---|---|---|')
for k in keys:
    for l in ('en', 'fr', 'es', 'tr'):
        o, n = old[l].get(k), new[l].get(k)
        if o == n: continue
        ov = '(new key)' if o is None and old['en'].get(k) is None else ('(missing: English was shown)' if o is None else esc(o))
        print(f'| `{k}` | {l} | {ov} | {esc(n)} |')
